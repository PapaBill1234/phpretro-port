def download(url, digest):
    data = urllib.request.urlopen(url, timeout=30).read()
    if hashlib.sha256(data).hexdigest() != digest:
        raise RuntimeError("verified fixture input checksum mismatch")
    return data

def main():
    with tempfile.TemporaryDirectory(prefix="phpretro-bcrypt-") as scratch:
        tmp = Path(scratch)
        for artifact, (version, digest) in ARTIFACTS.items():
            url = f"https://repo.maven.apache.org/maven2/at/favre/lib/{artifact}/{version}/{artifact}-{version}.jar"
            (tmp / f"{artifact}.jar").write_bytes(download(url, digest))
        source = download(f"https://raw.githubusercontent.com/duckietm/Polaris-Emulator/{POLARIS_SHA}/{SOURCE}", SOURCE_SHA256)
        (tmp / "PasswordHasher.java").write_bytes(source)
        (tmp / "Probe.java").write_text(JAVA)
        result = subprocess.run([
            "docker", "run", "--rm", "--network", "none", "--read-only", "--cap-drop", "ALL",
            "--security-opt", "no-new-privileges", "--tmpfs", "/tmp:rw,nosuid,nodev",
            "--user", f"{os.getuid()}:{os.getgid()}", "-v", f"{tmp}:/probe:rw", "-w", "/probe", IMAGE,
            "sh", "-c", "javac -cp 'bcrypt.jar:bytes.jar' -d . PasswordHasher.java Probe.java && java -cp '.:bcrypt.jar:bytes.jar' Probe",
        ], text=True, capture_output=True, timeout=90)
        if result.returncode:
            raise RuntimeError("Java bcrypt fixture probe failed")
        vectors = []
        for line in result.stdout.splitlines():
            ident, encoded, hashed = line.split("\t")
            vectors.append({"id": ident, "password": base64.b64decode(encoded).decode(), "hash": hashed})
        if len(vectors) != 4 or any(not row["hash"].startswith(("$2a$", "$2y$")) for row in vectors):
            raise RuntimeError("unexpected Java fixture output")
        image = json.loads(subprocess.check_output(["docker", "image", "inspect", IMAGE], text=True))[0]
        provenance = {"polarisCommit": POLARIS_SHA, "sourcePath": SOURCE, "sourceSHA256": SOURCE_SHA256,
                      "javaImage": image["RepoDigests"][0], "mavenArtifacts": ARTIFACTS,
                      "notes": "Synthetic passwords only. Random salts regenerated by the exact pinned Java PasswordHasher. Java verified positive, wrong-password, 2y, 72-byte, 73-byte rejection and malformed-hash cases."}
        (ROOT / "java-bcrypt-fixtures.json").write_text(json.dumps({"provenance": provenance, "vectors": vectors}, ensure_ascii=False, indent=2) + "\n")
        print("Java bcrypt fixture verified: 4 synthetic vectors; no emulator process or production data.")

if __name__ == "__main__":
    main()
